#!/usr/bin/env bash
# Flix v6 (Alienware, autonomous): waits for Flix v5 to finish (reports/flix_v5/ALL_DONE), then
# retrains the warm start on the v5 clips with audio that does not belong to the face on screen
# (silence, someone else's speech alone, someone talking over the speaker) and scores it once.
#   setsid nohup bash scripts/flix_v6_run.sh >> logs/flix_v6.log 2>&1 < /dev/null &
# Resumable; scripts/flix_boot.sh restarts it after a reboot.
set -uo pipefail
cd "$(dirname "$0")/.."
PY=.venv/bin/python
export PYTHONPATH=asr_pkgs:.
R=reports/flix_v6; S=$R/state; V5=reports/flix_v5/state; mkdir -p "$S" logs configs/flix_v6
note() { echo "- $(date '+%Y-%m-%d %H:%M') $*" | tee -a "$R/decision_log.md"; }

if [ ! -f "$R/decision_log.md" ]; then cat > "$R/decision_log.md" <<'NOTE'
# Flix v6 decision log

## Spec (written 15 Nov 2026, before any v6 run)

- **Why.** In use, the audio may not belong to the face on screen: the speaker may only mouth
  words (silence), or mouth them while other people talk. v4/v5 never trained on that: their
  noise is MUSAN non-speech only, and nothing checks that the voice matches the lips. With the
  audio stream switched off the v4 warm start reads lips at 48 % WER (TED) / 61 % (films).
- **Change (one).** Retrain the v5 warm start (fusion_gated_ws: same config, same frozen v5 twin
  and v5 fusion_wp streams) with data.interference: per training clip, p 0.10 silent (zeros, or
  MUSAN noise alone at −50..−30 dBFS), p 0.10 replace (another talk's / film's speech alone),
  p 0.15 talk-over (other speech at SIR −5..10 dB under the usual MUSAN noise). The label stays
  the on-screen speaker's words. best.pt is picked on the usual val sets plus ted/film × silent,
  replace (data.val_conditions).
- **Locked evaluation.** v5 test sets, once: clean, 0, −5, −10 dB; silent; talk-over at 0 dB;
  replace (scripts/flix_v6_eval.py). Models: twin_v5, ws_v5, ws_v6, and lips_v5 (ws_v5 with
  its audio switched off) as the lip-only reference.
- **Baseline.** ws_v5 under the same conditions.
- **Expected.** Best: ws_v6 on silent and replace within 5 points of lips_v5, talk-over well
  below ws_v5, ordinary conditions unchanged. Realistic: replace and silent 10–20 points above
  lips_v5 (the gate has to learn from features alone that the voice is not the speaker's),
  clean +0.5–1 point. Worst: the gate cannot tell a mismatched voice from a matching one, and
  replace stays near ws_v5.
- **Success.** ws_v6 beats ws_v5 on replace and silent (TED and films, CIs excluding 0), and is
  no more than 1 point worse than ws_v5 on clean TED.
- **Stop rule.** One training run; no tuning without the user. If the gate cannot detect a
  mismatched voice, the next step is an explicit audio-visual sync signal, not more of this.
NOTE
fi

# 1. wait for v5 ------------------------------------------------------------------------------
n=0
until [ -f reports/flix_v5/ALL_DONE ]; do
  [ $((n % 120)) -eq 0 ] && note "Waiting for Flix v5 (reports/flix_v5/ALL_DONE)."
  n=$((n + 1)); sleep 60
done

# 2. config: v5 warm start + interference -------------------------------------------------------
if [ ! -f configs/flix_v6/fusion_gated_ws.yaml ]; then
  $PY - <<'PYEOF' || { note "Config failed."; exit 1; }
import re
from pathlib import Path
t = Path("configs/flix_v5/fusion_gated_ws.yaml").read_text()
t = t.replace("experiment: flix_v5_", "experiment: flix_v6_")
add = """  interference:            # Flix v6: audio that does not belong to the face (GridDataset)
    p_silent: 0.10
    p_replace: 0.10
    p_talkover: 0.15
    sir_db: [-5.0, 10.0]
  val_conditions: [silent, replace]
"""
t, k = re.subn(r"(\n  tokenizer: subword\n)", r"\1" + add.replace("\\", "\\\\"), t, count=1)
assert k == 1 and "data/flix_v5/" in t and "runs/flix_v5/" in t
Path("configs/flix_v6/fusion_gated_ws.yaml").write_text(t.replace("# generated by scripts/flix_v5_run.sh",
                                                                    "# generated by scripts/flix_v6_run.sh from configs/flix_v5"))
PYEOF
  note "Config written: configs/flix_v6/fusion_gated_ws.yaml."
fi

# 3. train -----------------------------------------------------------------------------------
n=fusion_gated_ws
if [ ! -f "$S/$n.done" ]; then
  run=$(cat "$S/$n.run" 2>/dev/null || true)
  if [ -n "$run" ] && [ -f "$run/latest.pt" ]; then
    $PY -m scripts.train --resume "$run/latest.pt" --no-results >> "logs/flix_v6_$n.log" 2>&1 \
      || { note "Stage $n failed (logs/flix_v6_$n.log)."; exit 1; }
  else
    note "Stage $n started (configs/flix_v6/$n.yaml)."
    $PY -m scripts.train --config "configs/flix_v6/$n.yaml" --no-results --runs-root runs/flix_v6 \
        >> "logs/flix_v6_$n.log" 2>&1 &
    pid=$!
    for _ in $(seq 120); do
      run=$(grep -o "Run directory: .*" "logs/flix_v6_$n.log" | tail -1 | cut -d' ' -f3-)
      [ -n "$run" ] && [ -d "$run" ] && { echo "$run" > "$S/$n.run"; break; }; sleep 5
    done
    wait $pid || { note "Stage $n failed (logs/flix_v6_$n.log)."; exit 1; }
  fi
  best=$($PY - "$(cat $S/$n.run)" <<'PYEOF'
import csv, sys
rows = list(csv.DictReader(open(sys.argv[1] + "/history.csv")))
b = min(rows, key=lambda r: float(r["val_wer"]))
cols = [c for c in rows[0] if c.startswith("wer_")]
print(f"best epoch {b['epoch']}/{len(rows)}: mean val WER {float(b['val_wer']):.1%} ("
      + ", ".join(f"{c[4:]} {float(b[c]):.1%}" for c in cols) + ")")
PYEOF
)
  note "Stage $n done: $best. Run: $(cat $S/$n.run)"
  touch "$S/$n.done"
fi

# 4. one test evaluation ---------------------------------------------------------------------
if [ ! -f "$S/eval.done" ]; then
  $PY scripts/flix_v6_eval.py --run twin_v5="$(cat $V5/fusion_wp_audio.run)" ws_v5="$(cat $V5/fusion_gated_ws.run)" \
      ws_v6="$(cat $S/fusion_gated_ws.run)" >> logs/flix_v6_eval.log 2>&1 \
      || { note "Evaluation failed (logs/flix_v6_eval.log)."; exit 1; }
  { echo; echo "## Test results, $(date '+%Y-%m-%d %H:%M')"; echo; cat $R/test_results.md; } >> "$R/decision_log.md"
  touch "$S/eval.done"
fi
note "Flix v6 finished."
touch "$R/ALL_DONE"
