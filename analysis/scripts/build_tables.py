"""Build every analysis table from the raw results (standard library only).

    python analysis/scripts/build_tables.py            # from the repository root

Reads (never writes) the raw results:
  experiments/results.csv                       GRID: test WER/CER per model and SNR
  reports/<run>[_grammar]/hypotheses.csv        GRID: one row per test clip and SNR
  reports/flix_v4/test_results*.json, beam.json Films and TED, Flix v4 (summaries only)
  analysis/data/flix_v5_hyps.csv.gz             Films and TED, Flix v5 (one row per clip)
  analysis/data/flix_v6_hyps.csv.gz             Films and TED, Flix v6 (one row per clip)
Writes the tables under analysis/0*_*/tables/. Re-run it after new results arrive (e.g. X1-X3).
"""
from __future__ import annotations

import csv
import gzip
import json
import random
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AN = ROOT / "analysis"
SNR_ORDER = ["clean", "10", "5", "0", "-5", "-10"]

# GRID experiment name -> label used in the reports (see analysis/00_overview/models.md)
GRID_LABELS = {
    "b1_audio_only": "B1", "b1_mfcc39": "B1-A2 (MFCC, X5)", "b1_logmel_mfcc": "B1-A3 (log-Mel+MFCC, X5)",
    "b2_visual_only": "B2 v1 (Conv3D)", "b2_visual_only_v2": "B2 v2 (ResNet-18)",
    "b3_concat": "B3 v1", "b3_concat_v2": "B3 v2",
    "p_scratch": "P1 (from scratch)", "p_init_b2": "P2 (init B2 v1)", "p_init_b1_b2": "P3 (init B1+B2 v1)",
    "p_init_b1_b2_v2": "P4 (init B1+B2 v2)",
    "x1_no_modality_dropout": "X1 (P4, no modality dropout)", "x2_concat_fusion": "X2 (P4, concat fusion)",
    "x3_2d_frontend": "X3 (P4, 2D front end)",
}


# ---------------------------------------------------------------- scoring helpers

def edit_ops(r: list, h: list) -> tuple[int, list[int], int]:
    """Levenshtein distance, errors charged to each reference token, insertions."""
    n, m = len(r), len(h)
    d = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(n + 1): d[i][0] = i
    for j in range(m + 1): d[0][j] = j
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            d[i][j] = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (r[i - 1] != h[j - 1]))
    i, j, per, ins = n, m, [0] * n, 0
    while i > 0 or j > 0:
        if i > 0 and j > 0 and d[i][j] == d[i - 1][j - 1] + (r[i - 1] != h[j - 1]):
            per[i - 1] += r[i - 1] != h[j - 1]; i -= 1; j -= 1
        elif j > 0 and d[i][j] == d[i][j - 1] + 1:
            ins += 1; j -= 1
        else:
            per[i - 1] += 1; i -= 1
    return d[n][m], per, ins


def score_clip(ref: str, hyp: str) -> dict:
    rw, hw = ref.split(), hyp.split()
    e, per, ins = edit_ops(rw, hw)
    edge = {0, len(rw) - 1} if rw else set()
    ce, _, _ = edit_ops(list(ref), list(hyp))
    return {"word_err": e, "words": len(rw), "char_err": ce, "chars": len(ref),
            "edge_err": sum(per[p] for p in edge), "edge_words": len(edge),
            "inner_err": sum(per) - sum(per[p] for p in edge), "inner_words": max(0, len(rw) - len(edge))}


def pct(a: float, b: float) -> str:
    return f"{100 * a / b:.2f}" if b else ""


def bootstrap(groups_a: dict, groups_b: dict, n: int = 2000, seed: int = 0) -> tuple[float, float, float]:
    """Paired bootstrap of WER(a) - WER(b) in points, resampling whole groups (talks / films / speakers)."""
    keys = sorted(set(groups_a) & set(groups_b))
    rng = random.Random(seed); diffs = []
    for _ in range(n):
        s = [keys[rng.randrange(len(keys))] for _ in keys]
        ea = sum(groups_a[k][0] for k in s); eb = sum(groups_b[k][0] for k in s); w = sum(groups_a[k][1] for k in s)
        diffs.append(100 * (ea - eb) / w if w else 0.0)
    diffs.sort()
    ea = sum(groups_a[k][0] for k in keys); eb = sum(groups_b[k][0] for k in keys); w = sum(groups_a[k][1] for k in keys)
    return 100 * (ea - eb) / w, diffs[int(0.025 * n)], diffs[int(0.975 * n) - 1]


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)


def write_md(path: Path, title: str, note: str, header: list[str], rows: list[list]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    out = [f"# {title}", "", note, "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    path.write_text("\n".join(out) + "\n\n_Generated by analysis/scripts/build_tables.py; do not edit by hand._\n")


# ---------------------------------------------------------------- GRID

def grid() -> None:
    out = AN / "01_grid" / "tables"
    rows, seen = [], {}
    with open(ROOT / "experiments" / "results.csv", newline="") as f:
        for r in csv.DictReader(f):
            seen[r["experiment"]] = r                     # keep the latest row per experiment
    for exp, r in seen.items():
        label = GRID_LABELS.get(exp, exp)
        for decode, cond, col in [("greedy", "audio+video", "test_wer_by_snr"), ("grammar", "audio+video", "test_wer_by_snr_grammar"),
                                  ("greedy", "video only (audio dropped)", "test_wer_by_snr_no_audio"),
                                  ("greedy", "audio only (video dropped)", "test_wer_by_snr_no_visual")]:
            wer = dict(kv.split("=") for kv in (r.get(col) or "").split(";") if "=" in kv)
            cer = dict(kv.split("=") for kv in (r.get(col.replace("wer", "cer")) or "").split(";") if "=" in kv)
            for snr in SNR_ORDER:
                if snr in wer:
                    rows.append({"model": label, "experiment": exp, "run": Path(r["run_dir"]).name, "decode": decode,
                                 "condition": cond, "snr": snr, "wer_pct": f"{100 * float(wer[snr]):.2f}",
                                 "cer_pct": f"{100 * float(cer[snr]):.2f}" if snr in cer else ""})
    write_csv(out / "test_results_long.csv", rows)
    for decode in ("greedy", "grammar"):
        piv = defaultdict(dict)
        for x in rows:
            if x["decode"] == decode and x["condition"] == "audio+video":
                piv[x["model"]][x["snr"]] = x["wer_pct"]
        snrs = [s for s in SNR_ORDER if any(s in v for v in piv.values())]
        order = [l for l in GRID_LABELS.values() if l in piv]
        write_md(out / f"test_wer_{decode}.md", f"GRID test WER % ({decode} decoding)",
                 "Four unseen test speakers, 3,999 clips per SNR; fixed noisy test sets (W2-06). "
                 "Source: experiments/results.csv.", ["model"] + snrs, [[m] + [piv[m].get(s, "") for s in snrs] for m in order])
    mm = [x for x in rows if x["condition"] != "audio+video"]
    write_md(out / "missing_modality.md", "GRID test WER % with one stream removed at test time",
             "The model is unchanged; the dropped stream is replaced by e_miss (P) or zeros (B3). Source: experiments/results.csv.",
             ["model", "condition", "SNR", "WER %", "CER %"], [[x["model"], x["condition"], x["snr"], x["wer_pct"], x["cer_pct"]] for x in mm])
    # per speaker, from the per-clip hypotheses
    per = []
    for exp in ("b1_audio_only", "b3_concat_v2", "p_init_b1_b2_v2"):
        if exp not in seen:
            continue
        hyp = ROOT / "reports" / Path(seen[exp]["run_dir"]).name / "hypotheses.csv"
        if not hyp.exists():
            continue
        agg = defaultdict(lambda: [0.0, 0])
        with open(hyp, newline="") as f:
            for r in csv.DictReader(f):
                n = len(r["ref"].split()); agg[(r["speaker"], r["snr"])][0] += float(r["wer"]) * n; agg[(r["speaker"], r["snr"])][1] += n
        for (spk, snr), (e, n) in sorted(agg.items()):
            per.append({"model": GRID_LABELS[exp], "speaker": spk, "snr": snr, "wer_pct": pct(e, n), "words": n})
    write_csv(out / "per_speaker_wer.csv", per)


# ---------------------------------------------------------------- Films and TED (Flix)

def group_of(uid: str) -> str:
    """Film title or TED talk of a clip id (bootstrap and per-group tables resample these)."""
    u = uid[len("flix_"):] if uid.startswith("flix_") else uid
    return re.sub(r"_t\d+$", "", u) if u.startswith("ted_") else re.sub(r"_\d+$", "", u)


def load_hyps(name: str) -> list[dict]:
    p = AN / "data" / name
    if not p.exists():
        return []
    with gzip.open(p, "rt", newline="") as f:
        return list(csv.DictReader(f))


def flix() -> None:
    sources = {"films": AN / "02_films" / "tables", "ted": AN / "03_ted" / "tables"}
    src_of = lambda test: "films" if test.startswith(("film", "flix_test")) else "ted"
    # v4 summaries (no per-clip file kept for v4)
    v4 = []
    for f in ("test_results.json", "test_results_wp.json", "test_results_visual_old.json"):
        p = ROOT / "reports" / "flix_v4" / f
        if p.exists():
            for k, v in json.load(open(p)).items():
                model, test, snr = k.split("|")
                v4.append({"source": src_of(test), "version": "v4", "model": model, "test_set": test, "condition": snr,
                           "decode": "greedy", "wer_pct": f"{100 * v['wer']:.2f}", "cer_pct": f"{100 * v['cer']:.2f}", "n_clips": v["n"]})
    beam = ROOT / "reports" / "flix_v4" / "beam.json"
    if beam.exists():
        for model, v in json.load(open(beam)).items():
            for k, t in v["test"].items():
                test, snr = k.split("|")
                for dec in ("beam_no_lm", "beam_lm"):
                    v4.append({"source": src_of(test), "version": "v4", "model": model, "test_set": test, "condition": snr,
                               "decode": dec.replace("_", " + ").replace("beam + no + lm", "beam, no LM").replace("beam + lm", "beam + LM"),
                               "wer_pct": f"{t[dec]:.2f}", "cer_pct": "", "n_clips": t["n"]})
    # v5 and v6 from the per-clip snapshots
    clips = []
    for version, name in (("v5", "flix_v5_hyps.csv.gz"), ("v6", "flix_v6_hyps.csv.gz")):
        for r in load_hyps(name):
            s = score_clip(r["ref"], r["hyp"])
            clips.append({**r, **s, "version": version, "source": src_of(r["test_set"]), "group": group_of(r["utt_id"])})
    summary = defaultdict(lambda: defaultdict(float))
    for c in clips:
        k = (c["source"], c["version"], c["model"], c["test_set"], c["condition"])
        for f in ("word_err", "words", "char_err", "chars", "edge_err", "edge_words", "inner_err", "inner_words"):
            summary[k][f] += c[f]
        summary[k]["n"] += 1
    for src, out in sources.items():
        rows = [x for x in v4 if x["source"] == src]
        for (s, ver, model, test, cond), a in sorted(summary.items()):
            if s == src:
                rows.append({"source": s, "version": ver, "model": model, "test_set": test, "condition": cond, "decode": "greedy",
                             "wer_pct": pct(a["word_err"], a["words"]), "cer_pct": pct(a["char_err"], a["chars"]), "n_clips": int(a["n"])})
        write_csv(out / "test_results_long.csv", rows)
        # main table: the v5 test sets, every model and condition
        main = [r for r in rows if r["version"] in ("v5", "v6") and r["test_set"] in ("film_v5", "ted_v5", "film", "ted")]
        conds = [c for c in SNR_ORDER + ["silent", "talkover", "replace"] if any(r["condition"] == c for r in main)]
        models = sorted({(r["version"], r["model"]) for r in main}, key=lambda x: (x[1].split("_")[0] != "twin", x))
        piv = {(r["version"], r["model"], r["condition"]): r["wer_pct"] for r in main}
        write_md(out / "main_results.md", f"{'Films' if src == 'films' else 'TED'}: test WER % on the v5 test set (greedy)",
                 "v5 = padded re-cut clips with Whisper word-timestamp labels; v6 rows add the wrong-audio conditions. "
                 "Sources: analysis/data/flix_v5_hyps.csv.gz and flix_v6_hyps.csv.gz.",
                 ["version", "model"] + conds, [[v, m] + [piv.get((v, m, c), "") for c in conds] for v, m in models])
        # edge vs inner words
        ei = [[ver, model, test, cond, pct(a["edge_err"], a["edge_words"]), pct(a["inner_err"], a["inner_words"]), int(a["n"])]
              for (s, ver, model, test, cond), a in sorted(summary.items()) if s == src and ver == "v5"]
        write_md(out / "edge_vs_inner_words.md", "Error on the first/last word of a clip vs the inner words (v5 run)",
                 "Edge = first and last reference word. v4 sets = old tight clips; v5 sets = re-cut with 0.32 s padding.",
                 ["version", "model", "test set", "SNR", "edge-word err %", "inner-word err %", "clips"], ei)
        # per group (film title / TED talk) for the v5 test set
        g = defaultdict(lambda: [0, 0])
        for c in clips:
            if c["source"] == src and c["version"] == "v6" and c["condition"] in ("clean", "-10"):
                g[(c["model"], c["condition"], c["group"])][0] += c["word_err"]; g[(c["model"], c["condition"], c["group"])][1] += c["words"]
        write_csv(out / "per_group_wer.csv", [{"model": m, "condition": cond, "group": grp, "wer_pct": pct(e, w), "words": w}
                                              for (m, cond, grp), (e, w) in sorted(g.items())])
        # paired bootstrap of the key comparisons
        bs = []
        for a, b in (("ws_v5", "twin_v5"), ("ws_v6", "ws_v5")):
            for cond in conds:
                ga, gb = defaultdict(lambda: [0, 0]), defaultdict(lambda: [0, 0])
                for c in clips:
                    if c["source"] == src and c["version"] == "v6" and c["condition"] == cond:
                        tgt = ga if c["model"] == a else gb if c["model"] == b else None
                        if tgt is not None:
                            tgt[c["group"]][0] += c["word_err"]; tgt[c["group"]][1] += c["words"]
                if ga and gb:
                    d, lo, hi = bootstrap(ga, gb)
                    bs.append([f"{a} − {b}", cond, f"{d:+.2f}", f"[{lo:+.2f}, {hi:+.2f}]", len(ga)])
        write_md(out / "paired_bootstrap.md", "Paired bootstrap (WER points, 95 % CI), whole films / talks resampled",
                 "Negative = the first model is better. Computed from the v6 run's hypotheses (v5 test set).",
                 ["pair", "condition", "difference", "95 % CI", "groups"], bs)


def cross_source() -> None:
    out = AN / "04_cross_source" / "tables"
    rows = []
    g = AN / "01_grid" / "tables" / "test_results_long.csv"
    if g.exists():
        for r in csv.DictReader(open(g)):
            if r["decode"] == "greedy" and r["condition"] == "audio+video" and r["model"] in ("B1", "P4 (init B1+B2 v2)") and r["snr"] in ("clean", "-5"):
                rows.append(["GRID", r["model"], r["snr"], r["wer_pct"]])
    for src, name in (("02_films", "Films"), ("03_ted", "TED")):
        p = AN / src / "tables" / "test_results_long.csv"
        if p.exists():
            for r in csv.DictReader(open(p)):
                if r["version"] == "v6" and r["model"] in ("twin_v5", "ws_v5") and r["condition"] in ("clean", "-5", "-10"):
                    rows.append([name, r["model"], r["condition"], r["wer_pct"]])
    write_md(out / "headline.md", "Headline WER % per source (greedy)",
             "Audio-only baseline vs the audio + lips model on each source. GRID: B1 vs P4 (51-word vocabulary). "
             "Films and TED: twin_v5 vs ws_v5 (open vocabulary). Do not compare absolute WER across sources; compare the gap "
             "between the two models on each source.", ["source", "model", "SNR", "WER %"], rows)


if __name__ == "__main__":
    grid(); flix(); cross_source()
    print("tables written under", AN)
